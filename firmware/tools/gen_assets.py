# ----------------------------------------------------------------------------- fonts

def binarize(img):
    return img.point(lambda p: 255 if p > 127 else 0)

def crispness(size):
    """Lower mid-tone count == cleaner pixel grid at that size."""
    f = ImageFont.truetype(FONT, size)
    img = Image.new("L", (400, 60), 0)
    d = ImageDraw.Draw(img)
    d.text((2, 2), "Sub-GHz 433.92 MHz abcdefg 0123456789", font=f, fill=255)
    mid = sum(1 for p in img.getdata() if 40 < p < 215)
    return mid

def pick_size(target_cap):
    best, bestsize = None, None
    for size in range(8, 40):
        f = ImageFont.truetype(FONT, size)
        img = Image.new("1", (60, 60), 0)
        d = ImageDraw.Draw(img)
        d.text((2, 2), "H", font=f, fill=1)
        bb = img.getbbox()
        if not bb:
            continue
        cap = bb[3] - bb[1]
        if cap == target_cap:
            c = crispness(size)
            if best is None or c < best:
                best, bestsize = c, size
    if bestsize is None:
        raise SystemExit(f"no size yields cap height {target_cap}")
    return bestsize

class GlyphSet:
    def __init__(self, name, target_cap, bold=False, chars=None):
        size = pick_size(target_cap)
        self.name, self.size, self.bold = name, size, bold
        f = ImageFont.truetype(FONT, size)
        chars = chars or "".join(chr(c) for c in range(0x20, 0x7F))
        # measure baseline from 'H'
        probe = Image.new("L", (60, 60), 0)
        pd = ImageDraw.Draw(probe)
        pd.text((2, 2), "H", font=f, fill=255)
        self.baseline = probe.getbbox()[3] - 2          # rows from pen-top to H bottom
        self.glyphs = {}
        self.first, self.last = ord(chars[0]), ord(chars[-1])
        maxh = 0
        for ch in chars:
            img = Image.new("L", (80, 80), 0)
            d = ImageDraw.Draw(img)
            d.text((4, 4), ch, font=f, fill=255)
            bb = img.getbbox()
            adv = f.getlength(ch)
            adv = int(round(adv))
            if bb is None:
                self.glyphs[ch] = dict(adv=adv, w=0, h=0, dx=0, dy=0, data=b"")
                continue
            g = img.crop(bb).point(lambda p: 255 if p > 127 else 0)
            w, h = g.size
            if bold:
                g = g.point(lambda p: 255 if p else 0)
                src = g.load()
                out = Image.new("1", (w + 1, h), 0)
                od = out.load()
                for y in range(h):
                    for x in range(w):
                        if src[x, y] > 127:
                            od[x, y] = 1
                            od[x + 1, y] = 1
                g = out
                w, h = g.size
            px = g.load()
            rows = []
            for y in range(h):
                byte = 0
                bit = 7
                row = bytearray()
                for x in range(w):
                    if px[x, y] > 127:
                        byte |= 1 << bit
                    bit -= 1
                    if bit < 0:
                        row.append(byte); byte = 0; bit = 7
                if bit != 7:
                    row.append(byte)
                rows.append(bytes(row))
            dy = (bb[1] - 4) - (self.baseline - target_cap)   # ink top relative to baseline row
            self.glyphs[ch] = dict(adv=adv, w=w, h=h, dx=bb[0] - 4, dy=dy, data=b"".join(rows))
            maxh = max(maxh, h + max(0, dy))
        self.height = target_cap + 4      # baseline + descender room
        self.cap = target_cap

    def emit_c(self, fp):
        fp.write(f"\n/* font {self.name} (Micro5 @ {self.size}px"
                 f"{' bold' if self.bold else ''}) */\n")
        fp.write(f"static const uint8_t f_{self.name}_w[] = {{")
        for c in range(self.first, self.last + 1):
            fp.write(f"{self.glyphs[chr(c)]['w']},")
        fp.write("};\n")
        fp.write(f"static const int8_t f_{self.name}_dx[] = {{")
        for c in range(self.first, self.last + 1):
            fp.write(f"{self.glyphs[chr(c)]['dx']},")
        fp.write("};\n")
        fp.write(f"static const int8_t f_{self.name}_dy[] = {{")
        for c in range(self.first, self.last + 1):
            fp.write(f"{self.glyphs[chr(c)]['dy']},")
        fp.write("};\n")
        fp.write(f"static const uint8_t f_{self.name}_h[] = {{")
        for c in range(self.first, self.last + 1):
            fp.write(f"{self.glyphs[chr(c)]['h']},")
        fp.write("};\n")
        fp.write(f"static const uint8_t f_{self.name}_adv[] = {{")
        for c in range(self.first, self.last + 1):
            fp.write(f"{self.glyphs[chr(c)]['adv']},")
        fp.write("};\n")
        off, blob = 0, bytearray()
        offs = []
        for c in range(self.first, self.last + 1):
            offs.append(off)
            blob += self.glyphs[chr(c)]["data"]
            off += len(self.glyphs[chr(c)]["data"])
        fp.write(f"static const uint16_t f_{self.name}_off[] = {{")
        fp.write(",".join(str(o) for o in offs))
        fp.write("};\n")
        fp.write(f"static const uint8_t f_{self.name}_data[{len(blob)}] = {{")
        for i, b in enumerate(blob):
            if i % 16 == 0:
                fp.write("\n    ")
            fp.write(f"0x{b:02X},")
        fp.write("};\n")
        fp.write(f"const TfFont tf_{self.name} = {{ {self.first}, {self.last}, {self.height}, "
                 f"{self.cap}, f_{self.name}_w, f_{self.name}_h, f_{self.name}_dx, "
                 f"f_{self.name}_dy, f_{self.name}_adv, f_{self.name}_off, f_{self.name}_data }};\n")

