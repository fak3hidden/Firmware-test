def preview(fonts):
    """Render a mock of several real screens so the art can be checked by eye."""
    S = 4
    W, H = 128, 64
    def new():
        img = Image.new("1", (W, H), 1)
        return img, ImageDraw.Draw(img)
    def text(d, s, x, y, f, col=0, bg=None):
        px = 0
        for ch in s:
            g = f.glyphs.get(ch)
            if not g or g["w"] == 0:
                px += g["adv"] if g else 4
                continue
            gi = Image.new("1", (g["w"], g["h"]), 0)
            gp = gi.load()
            stride = (g["w"] + 7) // 8
            for yy in range(g["h"]):
                for xx in range(g["w"]):
                    if g["data"][yy * stride + xx // 8] >> (7 - xx % 8) & 1:
                        gp[xx, yy] = 1
            d.bitmap((x + px + g["dx"], y + g["dy"]), gi, fill=col)
            px += g["adv"]
        return px
    def icon_img(name):
        w, h, rows = ICONS[name]
        gi = Image.new("1", (w, h), 0)
        p = gi.load()
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == "#":
                    p[x, y] = 1
        return gi
    def dolph_img(name):
        w, h, rows = DOLPHIN[name]
        gi = Image.new("1", (w, h), 0)
        p = gi.load()
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == "#":
                    p[x, y] = 1
        return gi
    def statusbar(d):
        d.line([0, 11, 127, 11], fill=0)
        d.bitmap((109, 2), icon_img("st_battery"), fill=0)
        d.rectangle([111, 4, 118, 6], fill=0)
    frames = []
    # -- desktop with mascot
    img, d = new()
    d.bitmap((42, 14), dolph_img("idle0"), fill=0)
    statusbar(d)
    text(d, "T-Flipper", 3, 2, fonts[0])
    frames.append(("desktop", img))
    # -- main menu
    img, d = new()
    statusbar(d)
    text(d, "Main Menu", 3, 2, fonts[0])
    big = icon_img("subghz").resize((48, 48), Image.NEAREST)
    d.bitmap((4, 14), big, fill=0)
    items = ["Sub-GHz", "125 kHz RFID", "NFC", "Infrared", "iButton", "Bad USB"]
    y = 14
    for i, it in enumerate(items):
        if i == 0:
            d.rounded_rectangle([54, y - 1, 125, y + 9], radius=3, fill=0)
            text(d, it, 57, y + 1, fonts[0], col=1)
        else:
            text(d, it, 57, y + 1, fonts[0])
        y += 9
    frames.append(("main menu", img))
    # -- subghz read
    img, d = new()
    statusbar(d)
    text(d, "Sub-GHz Read", 3, 2, fonts[0])
    text(d, "433.92", 4, 18, fonts[3])
    text(d, "MHz", 62, 24, fonts[0])
    text(d, "Princeton", 4, 36, fonts[1])
    text(d, "Key: 0x1A2B3C", 4, 47, fonts[0])
    text(d, "SN: 0x00FF00", 4, 56, fonts[0])
    frames.append(("subghz read", img))
    # -- dialog
    img, d = new()
    d.rounded_rectangle([2, 8, 125, 58], radius=4, outline=0)
    text(d, "Save signal?", 10, 14, fonts[1])
    text(d, "Princeton 24bit", 10, 26, fonts[0])
    d.rounded_rectangle([8, 44, 60, 54], radius=3, outline=0)
    text(d, "Yes", 26, 46, fonts[0])
    d.rounded_rectangle([66, 44, 118, 54], radius=3, fill=0)
    text(d, "No", 86, 46, fonts[0], col=1)
    frames.append(("dialog", img))
    # -- keyboard
    img, d = new()
    statusbar(d)
    text(d, "Signal name", 3, 2, fonts[0])
    d.rectangle([2, 13, 125, 24], outline=0)
    text(d, "gate_remote_", 5, 15, fonts[0])
    d.line([5 + 62, 15, 5 + 62, 22], fill=0)
    keys = "qwertyuiop", "asdfghjkl", "zxcvbnm_-"
    ky = 30
    for row in keys:
        kx = 4
        for c in row:
            d.rectangle([kx, ky, kx + 10, ky + 9], outline=0)
            text(d, c, kx + 3, ky + 2, fonts[0])
            kx += 12
        ky += 10
    frames.append(("keyboard", img))
    tot_h = sum(im.height * S + 16 for _, im in frames)
    out = Image.new("L", (W * S + 10, tot_h + 6), 255)
    od = ImageDraw.Draw(out)
    lf = ImageFont.load_default()
    y = 3
    for label, im in frames:
        od.text((3, y + 12), label, font=lf, fill=0)
        bigim = im.resize((W * S, H * S), Image.NEAREST).convert("L")
        out.paste(bigim.point(lambda p: 255 if p > 127 else 0), (5, y))
        y += H * S + 16
