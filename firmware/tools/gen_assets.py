def param(name, w, h, fn):
    img = Image.new("1", (w, h), 0)
    d = ImageDraw.Draw(img)
    fn(d)
    rows = []
    px = img.load()
    for y in range(h):
        rows.append("".join("#" if px[x, y] else "." for x in range(w)))
    ICONS[name] = (w, h, rows)

