def emit_icon_c(path_h, path_c, table_name, icons, prefix):
    with open(path_c, "w") as fp:
        fp.write("/* generated by tools/gen_assets.py - do not edit */\n"
                 "#include \"assets.h\"\n\n")
        for name, (w, h, rows) in icons.items():
            bb = bytearray()
            for r in rows:
                byte = 0; bit = 7
                for chx in r:
                    if chx == "#":
                        byte |= 1 << bit
                    bit -= 1
                    if bit < 0:
                        bb.append(byte); byte = 0; bit = 7
                if bit != 7:
                    bb.append(byte)
            fp.write(f"static const uint8_t b_{prefix}{name}[] = {{\n    ")
            for i, b in enumerate(bb):
                if i and i % 16 == 0:
                    fp.write("\n    ")
                fp.write(f"0x{b:02X},")
            fp.write(f"\n}};\nconst TfIcon tfi_{prefix}{name} = {{ {w}, {h}, b_{prefix}{name} }};\n")
    with open(path_h, "w") as fp:
        fp.write("/* generated by tools/gen_assets.py - do not edit */\n#pragma once\n"
                 "#include \"assets.h\"\n\n")
        for name in icons:
            fp.write(f"extern const TfIcon tfi_{prefix}{name};\n")
        fp.write(f"\n#define {table_name}_COUNT {len(icons)}\n")

